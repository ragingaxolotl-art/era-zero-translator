import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {parseSentenceSequence,composeSentenceSequence} from '../pages/sentences.mjs';
import {midiFromFormal} from '../pages/engine.mjs';
import {scheduledLexicalEvents} from '../pages/scheduler.mjs';
const data=JSON.parse(fs.readFileSync(new URL('../pages/data/index.json',import.meta.url)));
const load=async target=>JSON.parse(fs.readFileSync(new URL(`../pages/${data.resolution_files[target]}`,import.meta.url))).variants['assertion:1'];
const input='Pip cares for Ada, then Ada is restoring Sol.';
const result=await composeSentenceSequence(input,load);
const ruby=JSON.parse(execFileSync('ruby',['-Itools/lib','-rera_zero_renderer','-rera_zero_presentation','-rbase64','-e','ir=JSON.parse(STDIN.read);f=EraZeroRenderer.render(ir);puts JSON.generate({formal:f,midi:Base64.strict_encode64(EraZeroPresentation.midi(f))})'],{cwd:new URL('..',import.meta.url),input:JSON.stringify(result.semantic_ir),encoding:'utf8',stdio:['pipe','pipe','pipe']}));
assert.deepEqual(result.formal,ruby.formal);
assert.deepEqual(Buffer.from(midiFromFormal(result.formal)),Buffer.from(ruby.midi,'base64'));
const events=scheduledLexicalEvents(result.formal);
assert.deepEqual(events.filter(event=>event.kind!=='phonemic_label'&&event.kind!=='grammar_marker').map(event=>event.target_id),['LIF:211','REP:111']);
assert.equal(events.find(event=>event.target_id==='LIF:211').boundary_after_beats,1);
const reverse=await composeSentenceSequence('Ada is restoring Sol, then Pip cares for Ada.',load);
assert.notDeepEqual(midiFromFormal(result.formal),midiFromFormal(reverse.formal));
assert.equal(parseSentenceSequence('Pip cares for Ada and Ada is restoring Sol.'),null);
assert.equal(parseSentenceSequence('Pip cares for Ada, then Ada is not restoring Sol tomorrow.'),null);
assert.equal(parseSentenceSequence('Pip cares for "then Ada".'),null);
assert.equal(parseSentenceSequence('It is possible that Pip cares for Ada, then Ada is restoring Sol.'),null);
console.log('Explicit sequences: whole-IR Ruby parity, exact MIDI parity, action order, clause boundary and unsupported-clause rejection pass.');
